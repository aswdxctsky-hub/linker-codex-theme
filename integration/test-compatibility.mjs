import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {findCompatibility,verifyArchive,sha256,validateCompatibility,COMPATIBILITY_URL} from './compatibility.mjs';
const root=await mkdtemp(join(tmpdir(),'linker-compat-test-'));
const pkg={family:'OpenAI.Codex_2p2nqsd0c76g0',version:'26.1029.9216.0'};
const doc=JSON.parse(await readFile(new URL('./compatibility.json',import.meta.url),'utf8'));
let requests=0;
const fetcher=async(url)=>{assert.equal(url,COMPATIBILITY_URL);requests++;return new Response(JSON.stringify(doc));};
assert.equal((await findCompatibility(root,pkg,{fetcher})).source,'github');
assert.equal((await findCompatibility(root,pkg,{fetcher})).source,'compatibility-cache.json');assert.equal(requests,1);
assert.equal((await findCompatibility(root,{...pkg,family:'wrong'},{fetcher})).entry,null);assert.equal(requests,1);
assert.equal((await findCompatibility(root,{...pkg,version:'99.1.1.0'},{online:false})).entry,null);
assert.equal((await findCompatibility(root,{...pkg,version:'99.1.1.0'},{fetcher:async()=>{throw Error('offline');}})).source,'unavailable');
assert.throws(()=>validateCompatibility({...doc,builds:[{...doc.builds[0],appAsarSha256:'not-a-hash'}]}));
assert.throws(()=>validateCompatibility({...doc,builds:[{...doc.builds[0],platform:'darwin'}]}));
assert.equal((await findCompatibility(root,{...pkg,version:'99.1.1.0'},{fetcher:async()=>new Response(JSON.stringify({...doc,builds:[{...doc.builds[0],version:'99.1.1.0',runtimeRevision:999}]}))})).entry,null);
const file=join(root,'app.asar'),cache=join(root,'archive-cache.json');
await writeFile(file,'verified build');const hash=await sha256(file);
assert.deepEqual(await verifyArchive(file,hash,cache),{valid:true,cached:false});
assert.deepEqual(await verifyArchive(file,hash,cache),{valid:true,cached:true});
assert.deepEqual(await verifyArchive(file,hash,cache,{force:true}),{valid:true,cached:false});
await writeFile(file,'different build');assert.equal((await verifyArchive(file,hash,cache)).valid,false);
const changed=await sha256(file);assert.deepEqual(await verifyArchive(file,changed,cache),{valid:true,cached:false});
